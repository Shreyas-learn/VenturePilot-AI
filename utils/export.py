def _build_styles() -> dict:
    """Return a dict of named ReportLab ParagraphStyle objects.

    Returns:
        Dictionary mapping style name → ParagraphStyle.
    """
    base = getSampleStyleSheet()

    return {
        "cover_title": ParagraphStyle(
            "VPCoverTitle",
            parent=base["Title"],
            fontSize=26,
            leading=32,
            spaceAfter=8,
            textColor=_COLOR_DARK,
            alignment=TA_CENTER,
        ),
        "cover_sub": ParagraphStyle(
            "VPCoverSub",
            parent=base["Normal"],
            fontSize=11,
            leading=16,
            spaceAfter=4,
            textColor=_COLOR_MUTED,
            alignment=TA_CENTER,
        ),
        "cover_score": ParagraphStyle(
            "VPCoverScore",
            parent=base["Normal"],
            fontSize=14,
            leading=20,
            spaceAfter=4,
            textColor=_COLOR_BLUE,
            alignment=TA_CENTER,
        ),
        "section_heading": ParagraphStyle(
            "VPSectionHeading",
            parent=base["Heading2"],
            fontSize=13,
            leading=18,
            spaceBefore=16,
            spaceAfter=6,
            textColor=_COLOR_BLUE,
            alignment=TA_LEFT,
        ),
        "body": ParagraphStyle(
            "VPBody",
            parent=base["Normal"],
            fontSize=10,
            leading=15,
            spaceAfter=6,
            textColor=_COLOR_DARK,
        ),
        "muted": ParagraphStyle(
            "VPMuted",
            parent=base["Normal"],
            fontSize=9,
            leading=13,
            spaceAfter=4,
            textColor=_COLOR_MUTED,
        ),
    }


