# Public API
# ---------------------------------------------------------------------------

def export_markdown(report) -> str:
    """Serialise a Report to Markdown and save it to the exports directory.

    Args:
        report: A :class:`core.report_builder.Report` instance.

    Returns:
        The full Markdown string (also written to disk).
    """
    lines: list[str] = [
        f"# {report.startup_input.startup_name} — Startup Blueprint",
        f"> Generated by {APP_NAME} v{APP_VERSION}  ",
        f"> {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        "",
        f"**Industry:** {report.startup_input.industry}  ",
        f"**Country:** {report.startup_input.country}  ",
        f"**Stage:** {report.startup_input.startup_stage}  ",
        f"**Budget:** {report.startup_input.budget}",
    ]

    if report.readiness_score is not None and report.readiness_score > 0:
        lines.append(
            f"**Startup Readiness Score:** {report.readiness_score} / 100"
        )

    lines += ["", "---", ""]

    for section in REPORT_SECTIONS:
        content = report.get_section(section)
        lines.append(f"## {section}")
        lines.append("")
        lines.append(content if content else "_Not generated._")
        lines.append("")

    markdown = "\n".join(lines)

    ensure_dir(settings.exports_dir)
    filename = _safe_filename(report.startup_input.startup_name) + "_blueprint.md"
    filepath = os.path.join(settings.exports_dir, filename)
    with open(filepath, "w", encoding="utf-8") as fh:
        fh.write(markdown)

    logger.info("Markdown report saved: %s", filepath)
    return markdown


def export_pdf(report) -> bytes:
    """Generate a PDF report and return the raw bytes.

    The PDF is also saved to the exports directory as a side effect.

    Args:
        report: A :class:`core.report_builder.Report` instance.

    Returns:
        PDF file contents as raw bytes.
    """
    ensure_dir(settings.exports_dir)
    filename = _safe_filename(report.startup_input.startup_name) + "_blueprint.pdf"
    filepath = os.path.join(settings.exports_dir, filename)

    styles = _build_styles()
    story  = _build_story(report, styles)

    doc = SimpleDocTemplate(
        filepath,
        pagesize=A4,
        leftMargin=2.2 * cm,
        rightMargin=2.2 * cm,
        topMargin=2 * cm,
        bottomMargin=2 * cm,
        title=f"{report.startup_input.startup_name} — Startup Blueprint",
        author=APP_NAME,
    )
    doc.build(story)
    logger.info("PDF report saved: %s", filepath)

    with open(filepath, "rb") as fh:
        return fh.read()


