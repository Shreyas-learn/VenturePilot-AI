"""
utils/export.py — PDF and Markdown export helpers.

Generates downloadable report files from a Report instance.
PDF generation uses ReportLab with a professional layout:
  - Cover page with startup name, metadata, and readiness score
  - Section headings styled in brand blue
  - Body text with proper line spacing
  - Safe HTML escaping to prevent ReportLab XML parse errors
  - All Markdown symbols stripped before rendering to PDF

Markdown export preserves all original Markdown formatting for
use in editors, GitHub, and document converters.
"""

import logging
import os
import re
from datetime import datetime
from io import BytesIO

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    HRFlowable,
    PageBreak,
    KeepTogether,
)
from reportlab.lib import colors

from config.settings import settings
from config.constants import APP_NAME, APP_VERSION, REPORT_SECTIONS
from utils.file_utils import ensure_dir

logger = logging.getLogger(__name__)

# Brand colour constants
_COLOR_DARK   = colors.HexColor("#1f2328")
_COLOR_BLUE   = colors.HexColor("#3b82d4")
_COLOR_MUTED  = colors.HexColor("#57606a")
_COLOR_BORDER = colors.HexColor("#e5e7eb")
_COLOR_BG     = colors.HexColor("#f7f8fa")


